namespace XSOverlayKeyboardIme.Input
{
    /// <summary>Virtual-key codes this plugin feeds to the composition host.</summary>
    internal enum VirtualKey : ushort
    {
        Back = 0x08,
        Tab = 0x09,
        Return = 0x0D,
        Shift = 0x10,
        Alt = 0x12,
        Escape = 0x1B,
        Space = 0x20,
        PageUp = 0x21,
        PageDown = 0x22,
        End = 0x23,
        Home = 0x24,
        Left = 0x25,
        Up = 0x26,
        Right = 0x27,
        Down = 0x28,
        Delete = 0x2E,
    }
}
